export const badgesOf = (kind: ReviewKind): BadgeDef[] =>
  kind === 'Похвала' ? PRAISE_BADGES : REMARK_BADGES

/** Значката по име (и по вид, ако името се среща и в двата списъка). */
export function findBadge(name: string, kind?: ReviewKind): BadgeDef | undefined {
  const pools = kind ? [badgesOf(kind)] : [PRAISE_BADGES, REMARK_BADGES]
  for (const pool of pools) {
    const hit = pool.find((b) => b.name === name)
    if (hit) return hit
  }
  return undefined
}

